#include <stdio.h>

int main() {
    //d[25] - массив, mi, ma - индексы мин, макс, s - сумма, p - произведение
    int n, d[25], mi = 0, ma = 0, s = 0, p = 1;

    //Ввод количества элементов
    printf("Введите количество элементов (n <= 25): ");
    if (scanf("%d", &n) != 1 || n <= 0 || n > 25) {
        printf("Некорректное значение n.\n");
        return 1;
    }

    //Ввод элементов массива и одновременный поиск мин,макс
    printf("Введите %d элементов массива:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &d[i]);
        if (d[i] < d[mi]) mi = i; // Находим индекс минимального
        if (d[i] > d[ma]) ma = i; // Находим индекс максимального
    }

    //Подсчет суммы предшествующих минимальному элементов (от 0 до mi-1)
    for (int i = 0; i < mi; i++) {
        s += d[i];
    }

    //Подсчет произведения последующих за максимальным элементов (от ma+1 до n-1)
    if (ma == n - 1) {
        p = 0; //Если максимум последний, последующих элементов нет (произведение = 0)
    } else {
        for (int i = ma + 1; i < n; i++) {
            p *= d[i];
        }
    }

    //Вывод требуемых по заданию характеристик с понятными указаниями
    putchar('\n');
    printf("Наименьшее значение: %d; номер: %d\n", d[mi], mi + 1);
    printf("Наибольшее значение: %d; номер: %d\n", d[ma], ma + 1);
    printf("Сумма элементов перед минимальным: %d\n", s);
    printf("Произведение элементов после максимального: %d\n", p);

    //Вывод измененного массива
    printf("\nИзмененный массив:\n");
    for (int i = 0; i < n; i++) {
        printf("%d ", d[i]);
    }
    printf("\n");

    return 0;
}
